-- Intelligent Class Schedule Management System - PostgreSQL schema
-- Run with:  npm run db:setup     (or paste into the Neon SQL Editor, then run seed.sql)
-- WARNING: running it again deletes all existing data.

DROP TABLE IF EXISTS offering_students, schedules, offerings, sections, terms, rooms, subject_skills, subject_fields, subjects,
  faculty_availability, faculty_subjects_taught, faculty_certifications, faculty_skills, faculty_degrees,
  faculty_profiles, login_attempts, sessions, users, skills, fields, departments, settings CASCADE;

-- ---------- Lookups ----------
CREATE TABLE departments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL
);

CREATE TABLE fields (            -- fields of study used for degree alignment
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE skills (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE settings (
  name VARCHAR(50) PRIMARY KEY,
  value VARCHAR(255) NOT NULL
);

-- ---------- Users, roles, and login sessions ----------
CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(120),
  role VARCHAR(10) NOT NULL CHECK (role IN ('admin', 'chair', 'faculty')),
  department_id INTEGER REFERENCES departments(id) ON DELETE SET NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE sessions (           -- one row per login; the cookie holds a random token, the table its SHA-256 hash
  id CHAR(64) PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_sessions_expires ON sessions (expires_at);

CREATE TABLE login_attempts (     -- failed logins, used to slow down password guessing
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL,
  attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_login_attempts ON login_attempts (username, attempted_at);

-- ---------- Faculty profiling ----------
CREATE TABLE faculty_profiles (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  employee_no VARCHAR(30),
  employment_status VARCHAR(10) NOT NULL DEFAULT 'full_time' CHECK (employment_status IN ('full_time', 'part_time')),
  academic_rank VARCHAR(60),
  max_units NUMERIC(4,1) NOT NULL DEFAULT 21,
  years_teaching INTEGER NOT NULL DEFAULT 0,
  industry_years INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE faculty_degrees (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  faculty_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  level VARCHAR(10) NOT NULL CHECK (level IN ('bachelor', 'master', 'doctorate')),
  title VARCHAR(150) NOT NULL,
  field_id INTEGER NOT NULL REFERENCES fields(id),
  institution VARCHAR(150) NOT NULL,
  year_graduated SMALLINT,
  status VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
  verified_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE faculty_skills (
  faculty_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
  proficiency SMALLINT NOT NULL DEFAULT 3 CHECK (proficiency BETWEEN 1 AND 5),   -- 1 basic ... 5 expert
  PRIMARY KEY (faculty_id, skill_id)
);

CREATE TABLE faculty_certifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  faculty_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL,
  issuer VARCHAR(150),
  year_obtained SMALLINT,
  skill_id INTEGER REFERENCES skills(id) ON DELETE SET NULL,     -- skill this credential proves
  status VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
  verified_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE faculty_availability (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  faculty_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day SMALLINT NOT NULL CHECK (day BETWEEN 1 AND 6),            -- 1 = Monday ... 6 = Saturday
  start_time TIME NOT NULL,
  end_time TIME NOT NULL
);

-- ---------- Subjects and their requirements ----------
CREATE TABLE subjects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  title VARCHAR(150) NOT NULL,
  units NUMERIC(3,1) NOT NULL DEFAULT 3,
  hours_per_week NUMERIC(3,1) NOT NULL DEFAULT 3,
  department_id INTEGER NOT NULL REFERENCES departments(id),
  min_degree_level VARCHAR(10) NOT NULL DEFAULT 'bachelor' CHECK (min_degree_level IN ('bachelor', 'master', 'doctorate')),
  room_type VARCHAR(10) NOT NULL DEFAULT 'lecture' CHECK (room_type IN ('lecture', 'laboratory'))
);

CREATE TABLE subject_fields (       -- degree fields accepted for the subject
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  field_id INTEGER NOT NULL REFERENCES fields(id) ON DELETE CASCADE,
  PRIMARY KEY (subject_id, field_id)
);

CREATE TABLE subject_skills (       -- skills needed to teach the subject
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
  PRIMARY KEY (subject_id, skill_id)
);

CREATE TABLE faculty_subjects_taught (   -- teaching history declared in the profile
  faculty_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  terms_taught INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (faculty_id, subject_id)
);

-- ---------- Scheduling ----------
CREATE TABLE rooms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE,
  building VARCHAR(80),
  capacity INTEGER NOT NULL DEFAULT 40,
  type VARCHAR(10) NOT NULL DEFAULT 'lecture' CHECK (type IN ('lecture', 'laboratory'))
);

CREATE TABLE terms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_year VARCHAR(20) NOT NULL,
  semester VARCHAR(20) NOT NULL CHECK (semester IN ('1st Semester', '2nd Semester', 'Summer')),
  is_active BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE (school_year, semester)
);

CREATE TABLE sections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE,
  program VARCHAR(80) NOT NULL,
  year_level SMALLINT NOT NULL DEFAULT 1,
  size INTEGER NOT NULL DEFAULT 40,
  department_id INTEGER NOT NULL REFERENCES departments(id)
);

CREATE TABLE offerings (             -- a subject offered to a section in a term
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term_id INTEGER NOT NULL REFERENCES terms(id) ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id),
  section_id INTEGER NOT NULL REFERENCES sections(id),
  enrolled INTEGER NOT NULL DEFAULT 0,   -- students enrolled in this class; must fit the room
  faculty_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  match_score NUMERIC(5,2),
  assigned_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  assigned_at TIMESTAMPTZ,
  UNIQUE (term_id, subject_id, section_id)
);

CREATE TABLE schedules (             -- one weekly meeting of an offering
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offering_id INTEGER NOT NULL REFERENCES offerings(id) ON DELETE CASCADE,
  room_id INTEGER NOT NULL REFERENCES rooms(id),
  day SMALLINT NOT NULL CHECK (day BETWEEN 1 AND 6),
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  CHECK (start_time < end_time)
);
CREATE INDEX idx_schedules_day_time ON schedules (day, start_time, end_time);

CREATE TABLE offering_students (     -- class list of an offering, printed as the List of Students form
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offering_id INTEGER NOT NULL REFERENCES offerings(id) ON DELETE CASCADE,
  position INTEGER NOT NULL,           -- order on the printed list, from 1
  name VARCHAR(150) NOT NULL           -- "SURNAME, First Name MI"
);
CREATE INDEX idx_offering_students ON offering_students (offering_id, position);
