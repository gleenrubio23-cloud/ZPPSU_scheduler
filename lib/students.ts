/**
 * Class lists: the students of one class offering, printed as the "List of Students" form.
 * The table is created on first use, so a database set up before this feature works without re-running db:setup.
 */
import { db, sql } from './db';

let ready: Promise<void> | null = null;

export function ensureStudentsTable(): Promise<void> {
  ready ??= db.exec(sql`
    CREATE TABLE IF NOT EXISTS offering_students (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      offering_id INTEGER NOT NULL REFERENCES offerings(id) ON DELETE CASCADE,
      position INTEGER NOT NULL,
      name VARCHAR(150) NOT NULL
    );
    CREATE INDEX IF NOT EXISTS idx_offering_students ON offering_students (offering_id, position)`)
    .then(() => undefined)
    .catch((err) => { ready = null; throw err; });
  return ready;
}

export async function classList(offeringId: number): Promise<string[]> {
  await ensureStudentsTable();
  return (await db.rows<{ name: string }>(sql`
    SELECT name FROM offering_students WHERE offering_id = ${offeringId} ORDER BY position`)).map((r) => r.name);
}

/** Number of listed students per offering, for the given offerings. */
export async function classListCounts(offeringIds: number[]): Promise<Map<number, number>> {
  if (!offeringIds.length) return new Map();
  await ensureStudentsTable();
  const rows = await db.rows<{ offering_id: number; n: number }>(sql`
    SELECT offering_id, COUNT(*) AS n FROM offering_students WHERE offering_id = ANY(${offeringIds}) GROUP BY offering_id`);
  return new Map(rows.map((r) => [r.offering_id, r.n]));
}

/** Split pasted text into clean names: one per line, blank lines and leading numbers ("1." / "1)") removed. */
export function parseNames(text: string): string[] {
  return text.split(/\r?\n/)
    .map((line) => line.replace(/^\s*\d+\s*[.)\-:]?\s+/, '').replace(/\s+/g, ' ').trim().slice(0, 150))
    .filter((line) => line && !/nothing follows/i.test(line));
}

/** "1st Semester" -> "First Semester" */
export function semesterWords(semester: string): string {
  return semester.replace(/^1st/, 'First').replace(/^2nd/, 'Second');
}
